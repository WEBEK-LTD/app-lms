#!/usr/bin/env node
/**
 * 172 Writes src/content/legal-history.ts: every version the privacy
 * policy, terms and refund policy's default text has had, in English, Arabic
 * and Turkish, from the git history of src/content/legal.ts,
 * src/content/ar/legal.ts and src/content/tr/legal.ts, plus the text in the
 * working tree. Admin › Website content compares a saved version with the
 * default it started from (lib/content/legal-updates.ts).
 *
 * Run it after changing a legal page's default text:
 *   node scripts/legal-history.mjs
 * tests/unit/legal-updates.test.ts fails while the file lacks the current text.
 * It needs the full history (`git fetch --unshallow` in a shallow clone).
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";
import ts from "typescript";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const FILES = { en: "src/content/legal.ts", ar: "src/content/ar/legal.ts", tr: "src/content/tr/legal.ts" };
const KEYS = ["privacy", "terms", "refund"];

/** The same hash as lib/content/legal-updates.ts › legalHash. */
function legalHash(d) {
  return createHash("sha256").update(`${d.title}\n${d.updated}\n${d.body}`).digest("hex").slice(0, 16);
}

function git(args) {
  return execFileSync("git", args, { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
}

/** The module's exports, from its TypeScript source (its imports are types only). */
function evaluate(source) {
  const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
  const cjs = { exports: {} };
  vm.runInNewContext(js, { module: cjs, exports: cjs.exports, require: () => ({}) });
  return cjs.exports;
}

/** { privacy, terms, refund } in a file's version: { title, updated, body } each, or nothing for a page it lacks. */
function pagesIn(lang, source) {
  const out = {};
  let exports;
  try {
    exports = evaluate(source);
  } catch {
    return out;
  }
  if (lang === "en") {
    for (const value of Object.values(exports)) {
      if (value && typeof value === "object" && KEYS.includes(value.key)) out[value.key] = value;
    }
  } else {
    const table = Object.values(exports).find((v) => v && typeof v === "object" && KEYS.some((k) => v[k]?.body));
    for (const key of KEYS) if (table?.[key]?.body) out[key] = table[key];
  }
  return out;
}

if (git(["rev-parse", "--is-shallow-repository"]).trim() === "true") {
  console.error("This clone is shallow: run `git fetch --unshallow` first, so every earlier version of the legal pages is found.");
  process.exit(1);
}

const history = {};
for (const [lang, file] of Object.entries(FILES)) {
  // Oldest first, following renames; the commit date is when the text reached main.
  const commits = git(["log", "--reverse", "--format=%H %cI", "--follow", "--", file])
    .trim()
    .split("\n")
    .filter(Boolean)
    .map((line) => line.split(" "));
  const versions = commits.map(([sha, date]) => ({ date, source: git(["show", `${sha}:${path.posix.join("platform/web", file)}`]) }));
  versions.push({ date: null, source: readFileSync(path.join(root, file), "utf8") });
  for (const { date, source } of versions) {
    const pages = pagesIn(lang, source);
    for (const key of KEYS) {
      const page = pages[key];
      if (!page) continue;
      const id = lang === "en" ? key : `${key}@${lang}`;
      const list = (history[id] ??= []);
      const entry = { hash: legalHash(page), since: date, title: page.title, updated: page.updated, body: page.body };
      if (list.some((e) => e.hash === entry.hash)) continue;
      // The working tree's text, when it isn't committed yet: dated today.
      if (entry.since === null) entry.since = new Date().toISOString();
      list.push(entry);
    }
  }
}

// One JSON string, not an object literal: TypeScript would infer a type for every version's text (too much memory for tsc).
const out = path.join(root, "src/content/legal-history.ts");
writeFileSync(
  out,
  [
    "// Generated by scripts/legal-history.mjs from the git history of src/content/legal.ts, ar/legal.ts and tr/legal.ts. Don't edit it: run the script.",
    'import type { LegalVersion } from "@/lib/content/legal-updates";',
    "",
    "/** Each legal page's default versions by language (\"privacy\", \"privacy@ar\" …), oldest first. */",
    `export const LEGAL_HISTORY: Record<string, LegalVersion[]> = JSON.parse(${JSON.stringify(JSON.stringify(history))});`,
    "",
  ].join("\n"),
);
for (const [id, list] of Object.entries(history)) console.log(`${id}: ${list.length} versions`);
