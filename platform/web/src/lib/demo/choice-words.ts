/** A product's choice words (lib/catalog/product-langs.ts `productWords`) in `lang`, those this list has; none: null. */
export function choiceWordsIn(words: readonly string[], lang: "ar" | "tr"): Record<string, string> | null {
  const out: Record<string, string> = {};
  for (const w of words) {
    const t = CHOICE_WORDS[w]?.[lang];
    if (t) out[w] = t;
  }
  return Object.keys(out).length ? out : null;
}
