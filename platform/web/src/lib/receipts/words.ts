const WORDS: Record<Lang, ReceiptWords> = { en, ar, tr };

export type ReceiptWordKey = keyof ReceiptWords;

/** A receipt word in `lang`, with its `{placeholders}` filled in. */
export function receiptWord(lang: Lang, key: ReceiptWordKey, values: Record<string, string> = {}): string {
  return WORDS[lang][key].replace(/\{(\w+)\}/g, (all, name: string) => values[name] ?? all);
}

/** Every language's words, for the tests. */
export function receiptWords(lang: Lang): ReceiptWords {
  return WORDS[lang];
}
