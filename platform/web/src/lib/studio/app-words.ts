/** The languages templates are written in; another one gets English. */
export const APP_WORDS = { en, ar, tr } as const;
export type AppWordsLang = keyof typeof APP_WORDS;

/** `word` in `lang` (English for another language), with `app` for the app's name. */
export function appWord(lang: string | null | undefined, word: AppWord, app: string): string {
  const dict: Record<AppWord, string> = lang === "ar" || lang === "tr" ? APP_WORDS[lang] : en;
  return dict[word].replaceAll("{app}", app);
}

/** The words a template writes in `lang` for the app named `app` (a section context's `w`). */
export function appWords(lang: string | null | undefined, app: string): (word: AppWord) => string {
  return (word) => appWord(lang, word, app);
}

const capital = <K extends string>(key: K) => (key.charAt(0).toUpperCase() + key.slice(1)) as Capitalize<K>;

/**
 * 129 A new premium element's and premium map's first words in `lang`, by their own keys: the motion & media
 * elements' (`motion…`), the content & commerce elements' (`premium…`) and a map's samples (`map…`).
 */
export function premiumAppWords(lang: string | null | undefined, app: string) {
  const w = appWords(lang, app);
  return {
    motion: (key: PremiumWord) => w(`motion${capital(key)}`),
    content: (key: PremiumText) => w(`premium${capital(key)}`),
    map: ((key) => w(`map${capital(key)}`)) as PremiumMapWords,
  };
}
