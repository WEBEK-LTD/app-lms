export const PANEL_WORDS: Record<PanelLang, PanelWords> = { en, ar, tr };

export function panelLang(query: string | null | undefined, acceptLanguage: string | null | undefined): PanelLang {
  if (query === "ar" || query === "tr" || query === "en") return query;
  const first = (acceptLanguage ?? "").toLowerCase().slice(0, 2);
  return first === "ar" || first === "tr" ? first : "en";
}

export function fill(text: string, values: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (_, k: string) => String(values[k] ?? ""));
}
