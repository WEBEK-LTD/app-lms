export const CM_WORDS: Record<CmLang, CmWords> = { en, ar, tr };

/** A word with its {placeholders} filled. */
export function fill(text: string, values: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`));
}

/** "5 min ago", "3h ago"… in the member's language. */
export function ago(w: CmWords, date: Date | string, now: Date = new Date()): string {
  const s = Math.max(0, (now.getTime() - new Date(date).getTime()) / 1000);
  if (s < 60) return w.justNow;
  if (s < 3600) return fill(w.minutesAgo, { n: Math.floor(s / 60) });
  if (s < 86400) return fill(w.hoursAgo, { n: Math.floor(s / 3600) });
  return fill(w.daysAgo, { n: Math.floor(s / 86400) });
}

/** 18,400 → "18.4K", in Western digits. */
export function compact(n: number): string {
  if (n >= 1000) return `${(n / 1000).toFixed(n >= 10000 ? 1 : 1).replace(/\.0$/, "")}K`;
  return String(n);
}
