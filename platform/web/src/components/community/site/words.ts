export const CM_LANGS = ["en", "ar", "tr"] as const;
export type CmLang = (typeof CM_LANGS)[number];
export const CM_DEFAULT_LANG: CmLang = "en";
/** The visitor's choice of language, kept for a year. */
export const CM_LANG_COOKIE = "community_lang";

export const CM_LANG_INFO: Record<CmLang, { native: string; dir: "ltr" | "rtl"; intl: string }> = {
  en: { native: "English", dir: "ltr", intl: "en-US" },
  ar: { native: "العربية", dir: "rtl", intl: "ar-EG-u-nu-latn" },
  tr: { native: "Türkçe", dir: "ltr", intl: "tr-TR" },
};

export function isCmLang(value: unknown): value is CmLang {
  return typeof value === "string" && (CM_LANGS as readonly string[]).includes(value);
}

