// 43 Writes lib/l10n/app_localizations_overlay.dart from the English ARB
// file: an AppLocalizations that answers each string with the owner's
// translation from a string pack when there is a valid one, else with the
// app's own (that language's, or English). Run after changing the ARB
// files: dart run tool/gen_l10n_overlay.dart
//
// A key the overlay doesn't cover fails to compile (the class must
// implement every AppLocalizations member), so it can't go stale silently.
import 'dart:convert';
import 'dart:io';

const output = 'lib/l10n/app_localizations_overlay.dart';

/// The overlay's Dart source, before formatting.
String overlaySource(Map<String, dynamic> arb) {
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_l10n_overlay.dart from app_en.arb.')
    ..writeln('// Do not edit: run `dart run tool/gen_l10n_overlay.dart`.')
    ..writeln()
    ..writeln("import '../core/l10n/string_overlay.dart';")
    ..writeln("import 'app_localizations.dart';")
    ..writeln()
    ..writeln(
      "/// The owner's strings ([StringOverlay]) over the app's own ([base]).",
    )
    ..writeln('class OverlayLocalizations extends AppLocalizations {')
    ..writeln('  OverlayLocalizations(this.base, this.overlay, super.locale);')
    ..writeln()
    ..writeln('  final AppLocalizations base;')
    ..writeln('  final StringOverlay overlay;');
  for (final entry in arb.entries) {
    final key = entry.key;
    if (key.startsWith('@')) continue;
    final meta = arb['@$key'];
    final placeholders =
        (meta is Map ? meta['placeholders'] : null) as Map<String, dynamic>? ??
        const {};
    out
      ..writeln()
      ..writeln('  @override');
    if (placeholders.isEmpty) {
      out.writeln("  String get $key => overlay.text('$key') ?? base.$key;");
      continue;
    }
    final params = [
      for (final p in placeholders.entries)
        '${_dartType((p.value as Map)['type'] as String?)} ${p.key}',
    ].join(', ');
    final names = placeholders.keys.toList();
    final args = names.map((n) => "'$n': $n").join(', ');
    out.writeln(
      "  String $key($params) => overlay.format('$key', {$args}) ?? "
      'base.$key(${names.join(', ')});',
    );
  }
  out.writeln('}');
  return out.toString();
}

String _dartType(String? type) => switch (type) {
  'int' => 'int',
  'double' => 'double',
  'num' => 'num',
  'DateTime' => 'DateTime',
  _ => 'String',
};

void main() {
  final arb = jsonDecode(
    File('lib/l10n/app_en.arb').readAsStringSync(),
  ) as Map<String, dynamic>;
  File(output).writeAsStringSync(overlaySource(arb));
  final format = Process.runSync('dart', ['format', output]);
  stdout.write(format.stdout);
  stderr.write(format.stderr);
  if (format.exitCode != 0) exit(format.exitCode);
}
